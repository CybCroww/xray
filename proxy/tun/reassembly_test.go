func TestMobileReassemblyBoundsIncompletePackets(t *testing.T) {
	for _, tc := range []struct {
		name, source, destination string
		ipHeader                  int
	}{
		{"IPv4", "10.0.0.1:1234", "10.0.0.2:53", ipv4HeaderSize},
		{"IPv6", "[fd00::1]:1234", "[fd00::2]:53", ipv6HeaderSize},
	} {
		t.Run(tc.name, func(t *testing.T) {
			s, err := NewStack(context.Background(), StackOptions{MTU: 1280, LowMemory: true}, nil)
			if err != nil {
				t.Fatal(err)
			}
			defer s.Close()
			cache := &s.(*stack).fragments
			baseline := new(reassembly)
			src := netip.MustParseAddrPort(tc.source)
			dst := netip.MustParseAddrPort(tc.destination)
			whole := summed(udpPacket(src, dst, bytes.Repeat([]byte{1}, 62<<10)))
			fragments := split(whole, 1200, 0)
			last := parseTestFragment(t, fragments[len(fragments)-1])
			for id := range uint32(fragmentsMost) {
				last.id = id
				if _, ready := cache.add(last); ready {
					t.Fatal("completed datagram with only its last fragment")
				}
				baseline.add(last)
				if cache.retainedBytes > mobileFragmentBytes {
					t.Fatalf("retained %d bytes, capacity is %d", cache.retainedBytes, mobileFragmentBytes)
				}
			}
			var capacity int
			for _, packet := range cache.packets {
				capacity += cap(packet.data)
			}
			if capacity == 0 || cache.retainedBytes != capacity || cache.retainedBytes >= baseline.retainedBytes {
				t.Fatalf("retained %d bytes in %d bytes of buffers, normal TUN retained %d", cache.retainedBytes, capacity, baseline.retainedBytes)
			}
			t.Logf("retained %d bytes with the mobile profile and %d with the normal TUN", capacity, baseline.retainedBytes)

			// A complete datagram can still make progress while the table is full.
			for i, encoded := range fragments {
				fragment := parseTestFragment(t, encoded)
				fragment.id = fragmentsMost
				got, ready := cache.add(fragment)
				if i == len(fragments)-1 {
					if !ready || !bytes.Equal(got.payload, whole[tc.ipHeader:]) {
						t.Fatalf("large datagram did not reassemble: ready=%t, length=%d", ready, len(got.payload))
					}
				} else if ready {
					t.Fatal("datagram completed prematurely")
				}
			}
			if cache.retainedBytes > mobileFragmentBytes {
				t.Fatalf("budget exceeded after reassembly: %d", cache.retainedBytes)
			}
		})
	}
}

func TestReassemblyClearsOnNetworkResetAndClose(t *testing.T) {
	s, err := NewStack(context.Background(), StackOptions{MTU: 1280, LowMemory: true}, nil)
	if err != nil {
		t.Fatal(err)
	}
	stack := s.(*stack)
	defer stack.Close()
	cache := &stack.fragments
	src, dst := netip.MustParseAddrPort("10.0.0.1:1234"), netip.MustParseAddrPort("10.0.0.2:53")
	before := summed(udpPacket(src, dst, bytes.Repeat([]byte{1}, 1800)))
	after := summed(udpPacket(src, dst, bytes.Repeat([]byte{2}, 1800)))
	first := split(before, 1200, 7)
	second := split(after, 1200, 7)
	cache.add(parseTestFragment(t, first[0]))
	stack.ResetFlows()
	if len(cache.packets) != 0 || cache.retainedBytes != 0 {
		t.Fatal("network reset retained fragments from the old path")
	}
	if _, ready := cache.add(parseTestFragment(t, second[1])); ready {
		t.Fatal("joined fragments from before and after the reset")
	}
	if p, ready := cache.add(parseTestFragment(t, second[0])); !ready || !bytes.Equal(p.payload, after[ipv4HeaderSize:]) {
		t.Fatal("could not reassemble a new datagram after the reset")
	}
	if len(cache.packets) != 0 || cache.retainedBytes != 0 {
		t.Fatal("completed datagram kept its reassembly reservation")
	}
	cache.add(parseTestFragment(t, first[0]))
	stack.Close()
	cache.add(parseTestFragment(t, second[1]))
	if len(cache.packets) != 0 || cache.retainedBytes != 0 {
		t.Fatal("closed stack retained fragments")
	}
}

func parseTestFragment(t *testing.T, wire []byte) packet {
	t.Helper()
	p, ok := parsePacket(wire, 0)
	if !ok || !p.fragment {
		t.Fatal("invalid fragment generated by test")
	}
	return p
}
